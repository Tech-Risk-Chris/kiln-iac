//! Emission of Terraform JSON. Output is a pure function of the resource
//! graph: keys are sorted and nothing depends on time, host or environment,
//! so the same source always yields the same bytes.

use crate::eval::Interp;
use serde_json::{json, Map as JMap, Value as J};

pub const MIN_ENGINE: &str = ">= 1.7.0";

fn nested(table: &std::collections::BTreeMap<String, std::collections::BTreeMap<String, J>>) -> J {
    let mut m = JMap::new();
    for (ty, items) in table {
        m.insert(ty.clone(), J::Object(items.clone().into_iter().collect()));
    }
    J::Object(m)
}

pub fn emit(it: &Interp, source: &str, moved: &[(String, String)]) -> String {
    let g = &it.graph;
    let mut root = JMap::new();
    root.insert(
        "//".into(),
        // File name only: the output must not depend on where kiln was invoked.
        J::String(format!(
            "Generated by Kiln from {}. Do not edit; change the source and rebuild.",
            source.rsplit('/').next().unwrap_or(source)
        )),
    );

    let mut tf = JMap::new();
    tf.insert("required_version".into(), json!(MIN_ENGINE));
    if !it.providers.is_empty() {
        let mut rp = JMap::new();
        for (name, req) in &it.providers {
            let mut p = JMap::new();
            p.insert("source".into(), json!(req.source));
            if let Some(v) = &req.version {
                p.insert("version".into(), json!(v));
            }
            rp.insert(name.clone(), J::Object(p));
        }
        tf.insert("required_providers".into(), J::Object(rp));
    }
    if let Some((ty, cfg)) = &g.backend {
        let mut b = JMap::new();
        b.insert(ty.clone(), cfg.clone());
        tf.insert("backend".into(), J::Object(b));
    }
    root.insert("terraform".into(), J::Object(tf));

    if !g.provider_cfg.is_empty() {
        let mut p = JMap::new();
        for (name, cfgs) in &g.provider_cfg {
            let v = if cfgs.len() == 1 { cfgs[0].clone() } else { J::Array(cfgs.clone()) };
            p.insert(name.clone(), v);
        }
        root.insert("provider".into(), J::Object(p));
    }
    if !g.data.is_empty() {
        root.insert("data".into(), nested(&g.data));
    }
    if !g.resources.is_empty() {
        root.insert("resource".into(), nested(&g.resources));
    }
    if !g.modules.is_empty() {
        root.insert("module".into(), J::Object(g.modules.clone().into_iter().collect()));
    }
    if !moved.is_empty() {
        let blocks = moved.iter().map(|(from, to)| json!({ "from": from, "to": to })).collect();
        root.insert("moved".into(), J::Array(blocks));
    }
    if !g.outputs.is_empty() {
        root.insert("output".into(), J::Object(g.outputs.clone().into_iter().collect()));
    }
    let mut s = serde_json::to_string_pretty(&J::Object(root)).expect("JSON serialisation");
    s.push('\n');
    s
}
